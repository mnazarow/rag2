"""
Единая нормализация текста для индекса и запроса.

Главное правило: индекс и запрос нормализуются ОДНОЙ функцией. Половина
дефектов поиска на реальной базе — это не «плохой алгоритм», а два
написания одного и того же по разные стороны совпадения:

  · «Водомёт» в паспорте и «водомет» в вопросе. Токенизатор FTS5
    unicode61 с remove_diacritics 2 НЕ сводит «ё» к «е» — проверено на
    живом SQLite. Пользователи же почти всегда печатают «е»;
  · «м³/ч» в одном документе и «м3/ч» в соседнем — а в вопросе вообще
    «кубов в час»;
  · «3,6» и «3.6» — одна подача, два токена.

Здесь только дешёвые посимвольные замены, безопасные для артикулов:
никакого стемминга, никакой замены слов. Всё, что меняет смысл, живёт
выше (словарь синонимов — в search, ремонт гомоглифов — в ocr).

После изменения этого файла индекс нужно пересобрать (python index.py
build --force или reembed): старые тексты в FTS нормализованы по-старому.
"""
from __future__ import annotations

import re

# Надстрочные и типографские символы → обычные.
_CHARMAP = str.maketrans({
    "ё": "е", "Ё": "Е",
    "³": "3", "²": "2", "¹": "1", "°": "",
    "Ø": "d", "ø": "d", "∅": "d",
    "×": "x", "–": "-", "—": "-", "−": "-",
    "«": '"', "»": '"',
})

# Варианты записи единиц → каноническая форма. Работает и в тексте
# документа, и в вопросе. Порядок важен: длинные шаблоны первыми.
_UNIT_RULES = [
    (re.compile(r"\bкуб\.?\s?м(?:етров)?\s*(?:/|в\s+)час\b", re.I), "м3/ч"),
    (re.compile(r"\bкубометр(?:ов|а)?\s+в\s+час\b", re.I), "м3/ч"),
    (re.compile(r"\bм3\s*/\s*час\b", re.I), "м3/ч"),
    (re.compile(r"\bм\.?\s?куб\.?\s*/\s*ч(?:ас)?\b", re.I), "м3/ч"),
    (re.compile(r"\bл\.?\s*/\s*мин\.?\b", re.I), "л/мин"),
    (re.compile(r"\bквт\b", re.I), "квт"),
]

# Десятичная запятая между цифрами → точка («3,6» → «3.6»).
_DECIMAL_RX = re.compile(r"(?<=\d),(?=\d)")


def canon(text: str) -> str:
    """
    Каноническое написание: символы, единицы, десятичные точки.

    Регистр НЕ трогается (это дело токенизатора), слова не заменяются,
    артикулы проходят без изменений — «500095.F» остаётся собой.
    """
    if not text:
        return text
    text = text.translate(_CHARMAP)
    text = _DECIMAL_RX.sub(".", text)
    for rx, repl in _UNIT_RULES:
        text = rx.sub(repl, text)
    return text
