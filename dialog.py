"""
Память диалога: уточняющие вопросы наследуют тему.

«Какой напор у Водомёт 55/75?» → ответ → «А цена?». Второй вопрос сам по
себе пуст: поиск по слову «цена» находит что угодно, и до появления
порога отказа бот уверенно отвечал про случайный товар, а после —
честно молчал. Правильное поведение третье: понять, что вопрос
продолжает разговор, и унаследовать из него модель и бренд.

Наследование детерминированное, без обращения к модели: из прошлых
реплик берутся подписи моделей («55/75»), артикулы и известные бренды, и
приклеиваются к новому вопросу для поиска. Дёшево, предсказуемо, легко
объяснить по трассировке. Переписывание через LLM дало бы больше, но
ценой обращения к модели на каждый уточняющий вопрос и нового источника
галлюцинаций в самом неожиданном месте — в формулировке запроса.

Память живёт в процессе (бот и телефония — отдельные процессы, у каждого
своя) и истекает по времени: вопрос через час — это новый разговор.
"""
from __future__ import annotations

import re
import threading
import time

import config
import logging_setup

log = logging_setup.get("answer")

# Подписи моделей и артикулы: «55/75», «0.5-40», «500095.F», «2ECO6-38».
_SIGNATURE_RX = re.compile(
    r"\b\d+(?:[.,]\d+)?(?:[/\-]\d+(?:[.,]\d+)?)+\b"
    r"|\b\d{4,8}(?:\.[A-ZА-Я0-9]{1,3})?\b"
    r"|\b[A-Za-z]+\d+[\w\-]*\b", re.IGNORECASE)

# Вопрос «пустой», если после отсева служебных слов в нём не осталось
# ни подписи модели, ни бренда, и мало содержательных слов. Именно такие
# вопросы продолжают разговор: «а цена?», «какая глубина погружения?»,
# «а у неё?».
_FILLER = {"а", "и", "но", "же", "ну", "как", "что", "какой", "какая", "какое",
           "какие", "сколько", "есть", "ли", "у", "на", "в", "по", "для", "не",
           "него", "неё", "нее", "них", "этой", "этого", "это", "эта", "тот",
           "той", "такой", "такая", "цена", "стоимость", "стоит", "почём"}

# Слова-характеристики: вопрос, состоящий только из них, спрашивает о
# свойстве обсуждаемого товара, а не о новом товаре. «Какая глубина
# погружения?» наследует модель из разговора; «сколько стоит кабель» —
# уже про другой предмет, наследовать нельзя: с чужой подписью модели
# ценовой канал нашёл бы не кабель, а прошлый насос.
_ATTRIBUTES = {"напор", "подача", "производительность", "расход", "давление",
               "мощность", "вес", "масса", "гарантия", "размер", "диаметр",
               "температура", "обороты", "шум", "ресурс", "комплект",
               "комплектация", "погружение", "погружения", "глубина", "длина",
               "высота", "ток", "напряжение", "артикул", "срок", "службы",
               "материал", "защита", "класс", "паспорт", "сертификат"}

_lock = threading.Lock()
_memory: dict[int, dict] = {}          # ключ разговора → {entities, ts, turns}


def _brands() -> set[str]:
    """Известные бренды — из той же базы, что использует канал эталонов."""
    try:
        import answer
        return answer._known_brands()
    except Exception:  # noqa: BLE001
        return set()


def extract_entities(text: str) -> list[str]:
    """Модель, артикул, бренд — то, что стоит унаследовать."""
    out: list[str] = []
    for m in _SIGNATURE_RX.findall(text or ""):
        if m.lower() not in (x.lower() for x in out):
            out.append(m)
    words = set(re.findall(r"[\wа-яё]+", (text or "").lower()))
    for b in sorted(words & _brands()):
        out.append(b)
    return out[:6]


def is_followup(question: str) -> bool:
    """
    Продолжает ли вопрос разговор, а не начинает новый.

    Да — когда в вопросе нет ни своей модели, ни бренда, и он либо пуст
    после отсева служебных слов («а цена?»), либо целиком состоит из
    слов-характеристик («какая глубина погружения?»). Вопрос с новым
    предметом («сколько стоит кабель») разговор не продолжает: чужая
    подпись модели увела бы ценовой канал к прошлому товару.
    """
    if extract_entities(question):
        return False                    # своя модель или бренд — вопрос самодостаточен
    tokens = [t for t in re.findall(r"[\wа-яё]+", (question or "").lower())
              if t not in _FILLER and len(t) > 2]
    if not tokens:
        return True
    return all(t in _ATTRIBUTES for t in tokens)


def remember(chat_key: int | None, question: str) -> None:
    """Запоминает сущности реплики. Пустые реплики память не затирают."""
    if chat_key is None:
        return
    entities = extract_entities(question)
    if not entities:
        return
    with _lock:
        _memory[chat_key] = {"entities": entities, "ts": time.time()}
        # Память не должна расти вечно: бот живёт неделями.
        if len(_memory) > 5000:
            cutoff = time.time() - config.DIALOG_MEMORY_MINUTES * 60
            for k in [k for k, v in _memory.items() if v["ts"] < cutoff]:
                del _memory[k]


def augment(chat_key: int | None, question: str) -> tuple[str, list[str]]:
    """
    Вопрос для поиска: уточняющий дополняется сущностями прошлой реплики.

    Возвращает (вопрос, унаследованные сущности). Текст пользователю не
    меняется — дополняется только то, что уходит в поиск и в модель;
    в трассировке видно и исходный вопрос, и наследование.
    """
    if chat_key is None or not config.DIALOG_MEMORY_MINUTES:
        return question, []
    if not is_followup(question):
        return question, []
    with _lock:
        past = _memory.get(chat_key)
    if not past:
        return question, []
    if time.time() - past["ts"] > config.DIALOG_MEMORY_MINUTES * 60:
        return question, []
    inherited = past["entities"]
    if not inherited:
        return question, []
    log.info("уточняющий вопрос «%s» унаследовал из разговора: %s",
             question[:60], ", ".join(inherited))
    return f"{question} ({' '.join(inherited)})", inherited


def reset() -> None:
    """Для тестов и смены настроек."""
    with _lock:
        _memory.clear()
