def _as_number(raw: str) -> float | None:
    try:
        return float(str(raw).replace(",", ".").strip())
    except (TypeError, ValueError):
        return None


def validate(values: dict[str, str], full: dict[str, str] | None = None) -> list[dict]:
    """
    Проверяет набор значений перед сохранением.

    Возвращает список замечаний. У каждого есть уровень: «error» — так
    сохранять нельзя, модуль не запустится; «warning» — необычно, но
    допустимо, если вы понимаете, что делаете.

    Проверяется четыре вещи: тип (число там, где ожидается число),
    допустимый список для перечислений, диапазон и связи между
    настройками. Последнее — самое ценное: выбрать onnx и не указать
    путь к модели легко, а обнаруживается это только при первом поиске.
    """
    by_key = {s["key"]: s for s in SETTINGS}
    merged = dict(full or {})
    merged.update(values)
    issues: list[dict] = []

    def add(key: str, level: str, text: str, hint: str = "") -> None:
        issues.append({"key": key, "level": level, "message": text, "hint": hint,
                       "title": by_key.get(key, {}).get("title", key)})

    for key, raw in values.items():
        spec = by_key.get(key)
        if spec is None:
            continue
        raw = "" if raw is None else str(raw).strip()
        kind = spec["type"]

        if kind == "bool":
            if raw not in ("0", "1", "true", "false", "True", "False", ""):
                add(key, "error", f"значение «{raw}» не подходит: нужно 0 или 1")
            continue

        if kind == "enum":
            options = spec.get("options") or []
            if raw and raw not in options:
                add(key, "error", f"«{raw}» — не из списка допустимых",
                    "Допустимо: " + ", ".join(options))
            continue

        if kind == "suggest":
            # Список — подсказка, а не закон: у облачных провайдеров имена
            # моделей меняются чаще, чем обновляется этот файл.
            continue

        if kind in ("int", "float"):
            if raw == "":
                add(key, "error", "пустое значение там, где нужно число")
                continue
            number = _as_number(raw)
            if number is None:
                add(key, "error", f"«{raw}» — это не число")
                continue
            if kind == "int" and abs(number - round(number)) > 1e-9:
                add(key, "error", f"нужно целое число, а не {raw}")
                continue
            bounds = RANGES.get(key)
            if bounds:
                hard_lo, soft_lo, soft_hi, hard_hi = bounds
                if number < hard_lo or number > hard_hi:
                    add(key, "error",
                        f"{raw} вне допустимого диапазона {hard_lo}…{hard_hi}",
                        spec.get("rec", ""))
                elif number < soft_lo or number > soft_hi:
                    add(key, "warning",
                        f"{raw} — необычное значение, обычно {soft_lo}…{soft_hi}",
                        spec.get("rec", ""))
            continue

        if kind in _PATHY and raw:
            from pathlib import Path as _P
            path = _P(raw).expanduser()
            if not path.exists():
                add(key, "warning", f"путь не существует: {path}",
                    "Он будет создан при первом обращении, если это папка "
                    "для данных, — но опечатку так тоже легко не заметить.")

    # Связи между настройками.
    for owner, triggers, needs, why in REQUIRED_WHEN:
        if merged.get(owner) in triggers and not str(merged.get(needs) or "").strip():
            add(needs, "error", f"не заполнено, а {owner}={merged.get(owner)}", why)

    # Отдельные смысловые проверки, которые не выражаются диапазоном.
    overlap = _as_number(merged.get("CHUNK_OVERLAP_CHARS", ""))
    target = _as_number(merged.get("CHUNK_TARGET_CHARS", ""))
    if overlap is not None and target is not None and overlap >= target:
        add("CHUNK_OVERLAP_CHARS", "error",
            "перекрытие не может быть больше самого фрагмента",
            "Обычно перекрытие — десятая часть длины фрагмента.")

    top_k = _as_number(merged.get("SEARCH_TOP_K", ""))
    candidates = _as_number(merged.get("SEARCH_CANDIDATES", ""))
    if top_k is not None and candidates is not None and top_k > candidates:
        add("SEARCH_TOP_K", "error",
            "в ответ просится больше фрагментов, чем поиск вообще отбирает",
            "SEARCH_TOP_K должен быть меньше SEARCH_CANDIDATES.")

    rerank_n = _as_number(merged.get("RERANKER_TOP_N", ""))
    if (top_k is not None and rerank_n is not None and merged.get("RERANKER_PROVIDER")
            not in (None, "", "none") and rerank_n < top_k):
        add("RERANKER_TOP_N", "warning",
            "пересортировывается меньше фрагментов, чем уходит в ответ",
            "Тогда переранжирование почти ни на что не влияет: "
            "сделайте его хотя бы вдвое больше SEARCH_TOP_K.")

    if merged.get("EMBEDDINGS_PROVIDER") == "hashing":
        add("EMBEDDINGS_PROVIDER", "warning",
            "hashing — заглушка без смысловой близости",
            "Поиск будет держаться на одном текстовом канале. "
            "Для работы выберите lsa или onnx.")

    if merged.get("LLM_PROVIDER") == "echo":
        add("LLM_PROVIDER", "warning",
            "echo — заглушка без модели",
            "Ответ собирается из найденных предложений. "
            "Для работы выберите провайдера и укажите ключ.")

    # Очередь к модели.
    slot_ttl = _as_number(merged.get("LLM_QUEUE_SLOT_TTL", ""))
    llm_timeout = _as_number(merged.get("LOCAL_LLM_TIMEOUT", ""))
    if slot_ttl is not None and llm_timeout is not None and slot_ttl <= llm_timeout:
        add("LLM_QUEUE_SLOT_TTL", "error",
            "срок жизни места в очереди не больше ожидания ответа модели",
            "Место освободится раньше, чем модель ответит, и его займёт "
            "второй запрос — ограничение перестанет работать именно на "
            "долгих ответах, ради которых оно и нужно. Ставьте хотя бы "
            "в полтора раза больше LOCAL_LLM_TIMEOUT.")

    queue_timeout = _as_number(merged.get("LLM_QUEUE_TIMEOUT", ""))
    queue_max = _as_number(merged.get("LLM_QUEUE_MAX", ""))
    concurrent = _as_number(merged.get("LLM_MAX_CONCURRENT", ""))
    if (queue_timeout is not None and queue_max is not None
            and llm_timeout is not None and concurrent is not None
            and concurrent >= 1 and queue_max >= 1):
        # Сколько в худшем случае ждёт последний в очереди.
        worst = queue_max * llm_timeout / max(concurrent, 1)
        if worst < queue_timeout / 2:
            add("LLM_QUEUE_MAX", "warning",
                "очередь короче, чем позволяет ждать таймаут",
                f"Даже полная очередь освободится примерно за {worst:.0f} с, "
                f"а ждать разрешено {queue_timeout:.0f} с. Отказы будут "
                "приходить по переполнению, а не по времени — это нормально, "
                "но тогда таймаут можно уменьшить.")

    if concurrent is not None and concurrent > 4 \
            and merged.get("LLM_PROVIDER") == "local":
        add("LLM_MAX_CONCURRENT", "warning",
            f"{concurrent:.0f} одновременных запросов к локальной модели",
            "На одной видеокарте это обычно замедляет каждый ответ, а не "
            "ускоряет обслуживание. Проверьте по разделу «Модели»: если "
            "среднее время самого запроса выросло — верните меньшее значение.")

    if concurrent == 0:
        add("LLM_MAX_CONCURRENT", "warning",
            "ограничение снято: запросы уходят к модели все сразу",
            "Для облачного провайдера это нормально. Для локальной модели "
            "означает, что при десяти одновременных вопросах не получит "
            "быстрый ответ никто, а при нехватке видеопамяти сервер модели "
            "упадёт.")

    if str(merged.get("ADMIN_HOST", "")) not in ("", "127.0.0.1", "localhost") \
            and not str(merged.get("ADMIN_TOKEN") or "").strip():
        add("ADMIN_TOKEN", "error",
            "админка слушает не только локальный адрес, а токен не задан",
            "Любой, кто дотянется до порта, получит полный доступ, "
            "включая восстановление индекса из копии.")

    order = {"error": 0, "warning": 1}
    issues.sort(key=lambda x: order.get(x["level"], 2))
    return issues


def as_json() -> list[dict]:
    """
    Всё, что нужно админке для одной карточки настройки.

    Кроме самого значения отдаются три вещи, которых раньше не хватало и
    из-за которых настройку приходилось искать в документации.

    Значение по умолчанию и признак «отличается от умолчания». Из ста
    девяноста настроек в реальной установке меняют десяток; без этого
    признака найти их среди остальных невозможно, а именно они и есть
    ответ на вопрос «что у нас настроено не как у всех».

    Допустимый диапазон — тот же, по которому проверка не даёт сохранить
    ерунду. Показывать границу после отказа поздно: правильнее видеть её
    сразу.

    Ключи и пароли не отдаются никогда: вместо значения приходит только
    признак, задано оно или нет. Пароль, приехавший в браузер, лежит в
    памяти вкладки, попадает в отладчик и в сохранённую страницу — а
    показывать его всё равно незачем.
    """
    out = []
    for s in SETTINGS:
        item = dict(s)
        value = current_value(s["key"])
        if s["type"] == "secret":
            item["value"] = ""
            item["filled"] = bool(str(value).strip())
        else:
            item["value"] = value
            item["filled"] = bool(str(value).strip())
        default = s.get("default", "")
        item["default"] = default
        item["is_default"] = (s["type"] != "secret"
                              and _same(value, default))
        bounds = RANGES.get(s["key"])
        if bounds:
            hard_lo, soft_lo, soft_hi, hard_hi = bounds
            item["range"] = {"min": hard_lo, "max": hard_hi,
                             "usual_min": soft_lo, "usual_max": soft_hi}
        out.append(item)
    return out


def _same(value, default) -> bool:
    """Сравнение значения с умолчанием, устойчивое к виду записи."""
    if isinstance(default, bool):
        return str(value).strip().lower() in (("1", "true", "yes")
                                              if default else ("0", "false", "no", ""))
    a, b = str(value).strip(), str(default).strip()
    if a == b:
        return True
    try:                       # 180 и 180.0 — одно и то же
        return abs(float(a) - float(b)) < 1e-9
    except (TypeError, ValueError):
        return False


def groups() -> list[dict]:
    """Разделы настроек со счётчиками — для навигации в админке."""
    items = as_json()
    out: list[dict] = []
    for item in items:
        if not out or out[-1]["name"] != item["group"]:
            out.append({"name": item["group"], "count": 0, "changed": 0})
        out[-1]["count"] += 1
        if not item["is_default"] and item["type"] != "secret":
            out[-1]["changed"] += 1
    return out


def to_env() -> str:
    lines = ["# Сгенерировано: python settings_schema.py env", ""]
    group = None
    for s in SETTINGS:
        if s["group"] != group:
            group = s["group"]
            lines.append(f"\n# ==== {group} " + "=" * max(4, 60 - len(group)))
        lines.append(f"# {s['title']}. {s['help']}")
        lines.append(f"# Рекомендация: {s['rec']}")
        if s.get("options"):
            lines.append(f"# Варианты: {', '.join(s['options'])}")
        lines.append(f"{s['key']}={s.get('default', '')}")
        lines.append("")
    return "\n".join(lines)


def to_markdown() -> str:
    counts = groups()
    lines = ["# Справочник настроек", "",
             f"Всего настроек: **{len(SETTINGS)}** в {len(counts)} разделах. "
             "Файл создаётся командой `python settings_schema.py md` из "
             "`settings_schema.py` — того же источника, откуда админка "
             "строит форму настроек. Поэтому справочник и экран настроек "
             "не могут разойтись: описание, рекомендация, пример, значение "
             "по умолчанию и допустимый диапазон везде одни и те же.", "",
             "Обычные настройки хранятся в `.env`, ключи и пароли — "
             "отдельно, в файле `SECRETS_FILE` с правами 600: он не "
             "попадает ни в архив обновления, ни в резервную копию.", "",
             "## Содержание", ""]
    for g in counts:
        anchor = g["name"].lower().replace(" ", "-")
        lines.append(f"- [{g['name']}](#{anchor}) — {g['count']}")
    lines.append("")

    group = None
    for s in SETTINGS:
        if s["group"] != group:
            group = s["group"]
            lines.append(f"\n## {group}\n")
        lines.append(f"### `{s['key']}` — {s['title']}\n")
        lines.append(s["help"] + "\n")
        lines.append(f"**Рекомендация.** {s['rec']}\n")
        if s.get("options"):
            lines.append("Допустимые значения: "
                         + ", ".join("`" + o + "`" for o in s["options"]) + "\n")
        bounds = RANGES.get(s["key"])
        if bounds:
            hard_lo, soft_lo, soft_hi, hard_hi = bounds
            lines.append(f"Допустимо от `{hard_lo}` до `{hard_hi}`, "
                         f"обычное значение — от `{soft_lo}` до `{soft_hi}`. "
                         "За мягкими границами сохранить можно, но система "
                         "переспросит.\n")
        if s["type"] == "secret":
            lines.append("Это ключ: хранится в защищённом файле, в "
                         "веб-интерфейсе не показывается.\n")
        else:
            default = s.get("default", "")
            shown = "пусто" if default == "" else default
            lines.append(f"По умолчанию: `{shown}`. Пример: "
                         f"`{s['key']}={s['example']}`\n")
    return "\n".join(lines)


